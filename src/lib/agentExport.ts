/**
 * Detect the actual model family from either the explicit provider field OR
 * the model id itself. Gateway-routed models often carry a `google/…` or
 * `anthropic/…` prefix even when `llm_provider` is something neutral like
 * `openrouter` — without this, gemini/claude models get wrapped with
 * ChatOpenAI and the OpenAI SDK rejects them at runtime.
 */
function detectFamily(provider: string, model: string): "google" | "anthropic" | "openai" {
  const p = (provider || "").toLowerCase();
  const m = (model || "").toLowerCase();
  if (p.includes("anthropic") || m.startsWith("anthropic/") || m.startsWith("claude-"))
    return "anthropic";
  if (
    p.includes("google") ||
    p.includes("gemini") ||
    p.includes("vertex") ||
    m.startsWith("google/") ||
    m.startsWith("gemini-") ||
    m.includes("/gemini-")
  ) {
    return "google";
  }
  return "openai";
}

function pyModelClass(
  provider: string,
  model = "",
): { importLine: string; cls: string; envVar: string } {
  const fam = detectFamily(provider, model);
  if (fam === "anthropic")
    return {
      importLine: "from langchain_anthropic import ChatAnthropic",
      cls: "ChatAnthropic",
      envVar: "ANTHROPIC_API_KEY",
    };
  if (fam === "google")
    return {
      importLine: "from langchain_google_genai import ChatGoogleGenerativeAI",
      cls: "ChatGoogleGenerativeAI",
      envVar: "GOOGLE_API_KEY",
    };
  return {
    importLine: "from langchain_openai import ChatOpenAI",
    cls: "ChatOpenAI",
    envVar: "OPENAI_API_KEY",
  };
}

