function pyToolStubs(tools: string[]): string {
  if (!tools.length) return "# No tools configured for this agent.\ntools: list = []\n";
  const stubs = tools.map((t) => {
    const fn = t.replace(/[^a-zA-Z0-9_]/g, "_");
    return `@tool\ndef ${fn}(query: str) -> str:\n    """${t} — implement your logic here."""\n    return f"${fn} result for: {query}"\n`;
  });
  return (
    stubs.join("\n") +
    `\ntools = [${tools.map((t) => t.replace(/[^a-zA-Z0-9_]/g, "_")).join(", ")}]\n`
  );
}

function tsToolStubs(tools: string[]): string {
  if (!tools.length)
    return "// No tools configured for this agent.\nconst tools: DynamicStructuredTool[] = [];\n";
  const stubs = tools.map((t) => {
    const fn = t.replace(/[^a-zA-Z0-9_]/g, "_");
    return `const ${fn}Tool = tool(\n  async ({ query }: { query: string }) => {\n    // TODO: implement ${t}\n    return \`${fn} result for: \${query}\`;\n  },\n  {\n    name: "${fn}",\n    description: "${t} — implement your logic here.",\n    schema: z.object({ query: z.string().describe("The input query") }),\n  }\n);\n`;
  });
  return (
    stubs.join("\n") +
    `\nconst tools = [${tools.map((t) => t.replace(/[^a-zA-Z0-9_]/g, "_") + "Tool").join(", ")}];\n`
  );
}

