#!/usr/bin/env node
// Generates the search index the documentation's search box filters.
//
// The docs are twenty-seven TSX pages with roughly three hundred and fifty
// headings between them. Without an index the only ways to find anything are
// the sidebar, which knows about pages and not sections, and the browser's own
// find, which knows about the page you already guessed correctly.
//
// The index is generated rather than hand-maintained for the same reason the
// consistency checker exists: a hand-written list is accurate on the day it is
// written. This reads the pages themselves, so a heading added tomorrow is
// searchable as soon as this runs.
//
//   node scripts/build-docs-index.mjs           write the index
//   node scripts/build-docs-index.mjs --check   fail if it is out of date (CI)
import fs from "node:fs";
import path from "node:path";

const ROUTES = "src/routes";
const OUT = "src/components/docs/docsIndex.ts";

const routeOf = (file) =>
  file === "docs.index.tsx"
    ? "/docs"
    : "/docs/" +
      file
        .replace(/^docs\./, "")
        .replace(/\.tsx$/, "")
        .replace(/\./g, "/");

/** Strip JSX/entities from a heading so the index holds what a reader sees. */
const plain = (s) =>
  s
    .replace(/\{"[^"]*"\}/g, " ")
    .replace(/<[^>]+>/g, "")
    .replace(/&amp;/g, "&")
    .replace(/&rarr;/g, "→")
    .replace(/&ldquo;|&rdquo;/g, '"')
    .replace(/&mdash;/g, "—")
    .replace(/\s+/g, " ")
    .trim();

const pages = [];
for (const file of fs
  .readdirSync(ROUTES)
  .filter((f) => /^docs\..+\.tsx$/.test(f))
  .sort()) {
  const src = fs.readFileSync(path.join(ROUTES, file), "utf8");
  const title = plain(src.match(/<DocsHeader[\s\S]*?title="([^"]+)"/)?.[1] ?? "");
  const description = plain(src.match(/<DocsHeader[\s\S]*?description="([^"]+)"/)?.[1] ?? "");
  const headings = [...src.matchAll(/<H([23])\s+id="([^"]+)"\s*>([\s\S]*?)<\/H\1>/g)]
    .map((m) => ({ id: m[2], text: plain(m[3]), level: Number(m[1]) }))
    .filter((h) => h.text);
  // Inline literals — chart types, tool ids, environment variables, field
  // names — are what people actually type into a search box, and almost none
  // of them are headings. Without these, searching "sankey" or
  // "ENFORCE_BUDGET_CAP" found nothing on pages that document both.
  const terms = [
    ...new Set(
      [...src.matchAll(/<C[^>]*>([^<{]{2,40})<\/C>/g)]
        .map((m) => plain(m[1]))
        .filter((t) => t && !/\s/.test(t)),
    ),
  ].sort();
  if (!title) continue;
  pages.push({ route: routeOf(file), title, description, terms, headings });
}

const body = `// GENERATED by scripts/build-docs-index.mjs — do not edit by hand.
//
// Run \`npm run docs:index\` after adding or renaming a documentation heading;
// \`npm run check:docs\` fails when this is stale, so it cannot quietly drift
// out of step with the pages it describes.

export type DocsIndexHeading = { id: string; text: string; level: number };
export type DocsIndexPage = {
  route: string;
  title: string;
  description: string;
  /** Inline literals on the page: tool ids, env vars, chart types, fields. */
  terms: string[];
  headings: DocsIndexHeading[];
};

export const DOCS_INDEX: DocsIndexPage[] = ${JSON.stringify(pages, null, 2)};
`;

const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
if (process.argv.includes("--check")) {
  if (current !== body) {
    console.error("docs index is stale — run: npm run docs:index");
    process.exit(1);
  }
  console.log(
    `docs index current: ${pages.length} pages, ${pages.reduce((n, p) => n + p.headings.length, 0)} headings.`,
  );
} else {
  fs.writeFileSync(OUT, body, "utf8");
  console.log(
    `wrote ${OUT}: ${pages.length} pages, ${pages.reduce((n, p) => n + p.headings.length, 0)} headings.`,
  );
}
