// Every service starts with every install.
//
// This file replaced composeProfiles.test.ts, which guarded the opposite
// arrangement: seven services behind compose profiles, and a check that each
// profiled service also carried `all` so `--profile all` could not silently
// skip one. That arrangement is gone. A product whose features depend on which
// flag the installer was given is a product most installs never see, and the
// support question "is X installed?" now has one answer.
//
// What must stay true: nothing in the compose file is profiled, the installers
// still accept the flags people have in their notes, and those flags change
// nothing about what runs.
import { readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";
import yaml from "js-yaml";

type ComposeFile = { services: Record<string, { profiles?: string[] }> };
const compose = yaml.load(readFileSync(resolve("docker-compose.yml"), "utf-8")) as ComposeFile;
const services = Object.entries(compose.services);
const setupSh = readFileSync(resolve("scripts/setup.sh"), "utf-8");
const setupPs = readFileSync(resolve("scripts/setup.ps1"), "utf-8");

const LEGACY_FLAGS = [
  "all",
  "docgen",
  "notebooks",
  "sandbox",
  "lakehouse",
  "spark",
  "vectors",
  "featurestore",
];

describe("docker compose starts the whole product", () => {
  it("declares no profiles at all, so `docker compose up -d` is the whole install", () => {
    const profiled = services
      .filter(([, s]) => Array.isArray(s.profiles) && s.profiles.length > 0)
      .map(([name]) => name);
    expect(
      profiled,
      `these services would not start on a plain up: ${profiled.join(", ")}`,
    ).toEqual([]);
  });

  it("ships the services the product needs, the object store included", () => {
    const names = services.map(([n]) => n);
    for (const required of [
      "agentswarms",
      "notebook-gateway",
      "notebook-egress",
      "notebook-docker-proxy",
      "lakehouse-catalog",
      "minio",
      "minio-init",
      "qdrant",
      "valkey",
      "spark-connect",
      "docgen",
      "js-sandbox",
    ]) {
      expect(names, `${required} is not in docker-compose.yml`).toContain(required);
    }
  });

  it("publishes every service a host-run app has to reach on loopback only", () => {
    // `scripts/setup.sh --dev` runs the app on the host and points .env at
    // 127.0.0.1, so development gets the same product rather than a subset.
    // Loopback, not 0.0.0.0: a vector store on a laptop's public interface is
    // a vector store the network can read.
    for (const name of ["qdrant", "valkey", "lakehouse-catalog", "spark-connect", "minio"]) {
      const ports = (compose.services[name] as { ports?: string[] }).ports ?? [];
      expect(ports.length, `${name} publishes no port for --dev`).toBeGreaterThan(0);
      for (const p of ports)
        expect(p, `${name} publishes ${p} beyond loopback`).toMatch(/^127\.0\.0\.1:/);
    }
  });
});

describe("the Spark Connect server authenticates and does not run as root (VA-23)", () => {
  const spark = compose.services["spark-connect"] as {
    command?: string[];
    environment?: Record<string, string>;
    user?: string;
  };
  const cmd = (spark.command ?? []).join("\n");

  it("drops the JVM to the unprivileged spark user via gosu", () => {
    expect(cmd).toContain("exec gosu spark /opt/spark/sbin/start-connect-server.sh");
    // No path that runs the server directly as the container user (root).
    expect(cmd).not.toMatch(/\n\s*\/opt\/spark\/sbin\/start-connect-server\.sh/);
  });

  it("fixes the cache ownership once, only when it is not already spark's", () => {
    expect(cmd).toContain("stat -c %u /tmp/ivy");
    expect(cmd).toContain("chown -R spark:spark /tmp/ivy");
  });

  it("enforces a token only when SPARK_CONNECT_TOKEN is set", () => {
    expect(cmd).toMatch(/if \[ -n "\$\$SPARK_CONNECT_TOKEN" \]/);
    expect(cmd).toContain('export SPARK_CONNECT_AUTHENTICATE_TOKEN="$$SPARK_CONNECT_TOKEN"');
    expect(spark.environment?.SPARK_CONNECT_TOKEN).toBe("${SPARK_CONNECT_TOKEN:-}");
  });

  it("is generated by the installers and shipped in .env.example", () => {
    expect(setupSh).toContain('setenv SPARK_CONNECT_TOKEN "$(gen_secret)"');
    expect(setupPs).toContain('Set-EnvVar "SPARK_CONNECT_TOKEN" (New-Secret)');
    expect(readFileSync(resolve(".env.example"), "utf-8")).toContain("SPARK_CONNECT_TOKEN=");
  });
});

describe("the feature store and the vector store take a password (VA-41)", () => {
  // Both sit on `default` with spark-connect, where Spark pipelines' Python UDFs
  // run; from there valkey answered DBSIZE and Qdrant listed its collections,
  // with no credentials (R411).
  const valkey = compose.services.valkey as unknown as {
    command: string[];
    environment: Record<string, string>;
    healthcheck: { test: string[] };
  };

  it("starts valkey with requirepass from VALKEY_PASSWORD, which may be empty", () => {
    const i = valkey.command.indexOf("--requirepass");
    expect(i).toBeGreaterThan(-1);
    expect(valkey.command[i + 1]).toBe("${VALKEY_PASSWORD:-}");
    expect(valkey.environment.VALKEY_PASSWORD).toBe("${VALKEY_PASSWORD:-}");
  });

  it("checks valkey's health with the password and by its PONG, not by valkey-cli's exit code", () => {
    // valkey-cli exits 0 on a NOAUTH reply, so a ping without the password
    // would call a store that refuses everyone healthy.
    const test = valkey.healthcheck.test.join(" ");
    expect(test).toContain('$${VALKEY_PASSWORD:+-a "$$VALKEY_PASSWORD" --no-auth-warning}');
    expect(test).toMatch(/ping \| grep -q PONG$/);
  });

  it("has the installers generate both, with the same Qdrant key on the server and the app", () => {
    expect(setupSh).toContain('setenv VALKEY_PASSWORD "$(gen_secret)"');
    expect(setupPs).toContain('Set-EnvVar "VALKEY_PASSWORD" (New-Secret)');
    expect(setupSh).toMatch(
      /Q_KEY="\$\(getenv QDRANT_API_KEY\)"[\s\S]*?setenv QDRANT_API_KEY "\$Q_KEY"[\s\S]*?setenv QDRANT__SERVICE__API_KEY "\$Q_KEY"/,
    );
    expect(setupPs).toMatch(
      /\$qKey = Get-EnvVar "QDRANT_API_KEY"[\s\S]*?Set-EnvVar "QDRANT_API_KEY" \$qKey[\s\S]*?Set-EnvVar "QDRANT__SERVICE__API_KEY" \$qKey/,
    );
    const example = readFileSync(resolve(".env.example"), "utf-8");
    expect(example).toMatch(/^VALKEY_PASSWORD=""$/m);
  });
});

describe("only the app can reach the Docker socket proxy (VA-40)", () => {
  // The proxy's sections are coarse: with CONTAINERS and POST on, a caller can
  // create a privileged container or mount the host, which is the host. It sat
  // on `default`, where spark-connect (which runs Spark pipelines' Python UDFs
  // and is on the kernels' network), the renderer and the gateway reached it.
  type Svc = { networks?: string[] | Record<string, unknown>; ports?: string[] };
  const svc = compose.services as Record<string, Svc>;
  const nets = (s: Svc) => (Array.isArray(s.networks) ? s.networks : Object.keys(s.networks ?? {}));
  const networks = (compose as unknown as { networks: Record<string, { internal?: boolean }> })
    .networks;

  it("puts the proxy on its own network, shared with the app and nothing else", () => {
    expect(nets(svc["notebook-docker-proxy"])).toEqual(["docker-api"]);
    const members = Object.entries(svc)
      .filter(([, s]) => nets(s).includes("docker-api"))
      .map(([name]) => name)
      .sort();
    expect(members).toEqual(["agentswarms", "notebook-docker-proxy"]);
  });

  it("publishes no port and keeps the network internal, because either opens it to every network", () => {
    // Measured on Docker Desktop (R408): a container's published port, even one
    // bound to 127.0.0.1, answered by IP from containers on other networks; an
    // unpublished one, and anything on an internal network, did not.
    expect(svc["notebook-docker-proxy"].ports ?? []).toEqual([]);
    expect(networks["docker-api"]?.internal).toBe(true);
  });

  it("has --dev tell the developer how to start a loopback proxy, with compose's sections only", () => {
    // R408 took the proxy's host port away, and --dev runs the app on the host:
    // without this, notebooks under --dev could not start a kernel and nothing
    // said why (R410). The installers print the command; they do not run it.
    const env = (
      compose.services["notebook-docker-proxy"] as { environment?: Record<string, string> }
    ).environment!;
    const flags = Object.keys(env)
      .map((k) => `${k}=${env[k]}`)
      .sort();
    const deployment = readFileSync(resolve("docs/DEPLOYMENT.md"), "utf-8");
    for (const [name, text, devStart] of [
      ["setup.sh", setupSh, 'if [ "$MODE" = "dev" ]; then\n  # The Docker socket proxy'],
      // .gitattributes checks setup.ps1 out with CRLF, on Linux CI too.
      ["setup.ps1", setupPs.replace(/\r\n/g, "\n"), "if ($Dev) {\n  # The Docker socket proxy"],
      ["DEPLOYMENT.md", deployment, "Running the app on the host with `npm run dev`?"],
    ] as const) {
      const at = text.indexOf(devStart);
      expect(at, `${name}: the dev-mode note`).toBeGreaterThan(-1);
      const block = text.slice(at, at + 1200);
      expect(block, name).toContain("-p 127.0.0.1:2375:2375");
      expect(block, name).toContain("agentswarms/docker-socket-proxy:latest");
      // Exactly compose's sections: one more (EXEC, VOLUMES...) is one more way in.
      const cmd = block.slice(0, block.indexOf("agentswarms/docker-socket-proxy:latest"));
      const given = [...cmd.matchAll(/-e (\w+=\S+)/g)].map((m) => m[1]).sort();
      expect(given, name).toEqual(flags);
      if (name !== "DEPLOYMENT.md") {
        expect(block.indexOf("docker run"), `${name}: printed, not run`).toBeLessThan(
          block.indexOf("npm run dev"),
        );
        expect(block, `${name}: printed, not run`).not.toMatch(/^\s*docker run/m);
      }
    }
  });

  it("has verify-runtime.sh find the proxy through its container, since the host cannot reach it", () => {
    // HEAD's check, run on this layout, reported the proxy missing.
    const verify = readFileSync(resolve("deploy/notebooks/test/verify-runtime.sh"), "utf-8");
    const fallback = verify.slice(verify.indexOf('if [ -z "$PROXY" ]; then'));
    expect(fallback).toContain("--filter label=com.docker.compose.service=notebook-docker-proxy");
    expect(fallback).toMatch(/"\$DOCKER" exec "\$pc" wget -qO- http:\/\/127\.0\.0\.1:2375\/_ping/);
    // ...and a success there sets PROXY before the pass/fail line reads it.
    const block = fallback.slice(0, fallback.indexOf('if [ -n "$PROXY" ]'));
    expect(block).toMatch(/\n\s+PROXY="[^"]+"/);
  });
});

describe("the installers", () => {
  it.each(LEGACY_FLAGS)("still accept --%s and do nothing with it", (flag) => {
    expect(setupSh, `setup.sh rejects --${flag}`).toMatch(
      new RegExp(
        `--all\\|--docgen\\|--notebooks\\|--sandbox\\|--lakehouse\\|--spark\\|--vectors\\|--featurestore\\) ;;`,
      ),
    );
    const sw = flag[0].toUpperCase() + flag.slice(1);
    expect(setupPs, `setup.ps1 has no -${sw}`).toContain(`[switch]$${sw}`);
  });

  it("start everything with one plain compose command, in both modes", () => {
    expect(setupSh).toContain("docker compose up -d --build");
    expect(setupSh).not.toMatch(/docker compose \$PROFILE_FLAGS/);
    expect(setupPs).toContain("docker compose up -d --build");
    expect(setupPs).not.toContain("@profiles");
  });

  it("point .env at every service, and at loopback when the app runs on the host", () => {
    for (const key of [
      "QDRANT_URL",
      "FEATURE_STORE_URL",
      "SPARK_CONNECT_URL",
      "LAKEHOUSE_S3_ENDPOINT",
    ]) {
      expect(setupSh, `setup.sh does not set ${key} for --dev`).toContain(`setenv ${key} `);
      expect(setupPs, `setup.ps1 does not set ${key} for -Dev`).toContain(`Set-EnvVar "${key}"`);
    }
    // The catalog password exists in two places that must carry the same value.
    expect(setupSh).toContain("setenv LAKEHOUSE_CATALOG_PASSWORD");
    expect(setupSh).toContain("setenv LAKEHOUSE_CATALOG_URL");
    expect(setupPs).toContain('Set-EnvVar "LAKEHOUSE_CATALOG_PASSWORD"');
    expect(setupPs).toContain('Set-EnvVar "LAKEHOUSE_CATALOG_URL"');
  });

  it(".env.example arrives wired, for the operator who never runs an installer", () => {
    // compose's own header tells people to `cp .env.example .env` and run
    // `docker compose up -d --build`. That path has to produce the same
    // product the installer does.
    const env = readFileSync(resolve(".env.example"), "utf-8");
    for (const line of [
      'VECTOR_STORE="qdrant"',
      'QDRANT_URL="http://qdrant:6333"',
      'FEATURE_STORE_URL="redis://valkey:6379"',
      'SPARK_CONNECT_URL="sc://spark-connect:15002"',
      'LAKEHOUSE_DATA_URL="s3://lakehouse/main"',
      'LAKEHOUSE_S3_ENDPOINT="minio:9000"',
      "LAKEHOUSE_CATALOG_URL=",
    ]) {
      expect(env, `.env.example does not set ${line}`).toContain(line);
    }
  });
});

describe("every third-party image is pinned by digest (VA-24)", () => {
  // tag@sha256:<64 hex> — the engine pulls by the digest, the tag is for people.
  const PINNED = /^[a-z0-9][a-z0-9./_-]*:[\w.-]+@sha256:[0-9a-f]{64}$/;
  // Images this repo builds itself; their tag names a local build, not a pull.
  const firstParty = (image: string) => /^agentswarms(\/|:)/.test(image);

  const k8sFiles = (dir: string): string[] =>
    readdirSync(resolve(dir), { withFileTypes: true }).flatMap((e) =>
      e.isDirectory()
        ? k8sFiles(join(dir, e.name))
        : /\.ya?ml$/.test(e.name)
          ? [join(dir, e.name)]
          : [],
    );
  const imageLines = (file: string) =>
    [...readFileSync(resolve(file), "utf-8").matchAll(/^\s*-?\s*image:\s*(\S+)/gm)].map(
      (m) => m[1],
    );

  const composeImages = Object.entries(
    (compose as unknown as { services: Record<string, { image?: string }> }).services,
  ).flatMap(([name, s]) => (s.image ? [[name, s.image] as const] : []));

  it("pins every image docker compose pulls", () => {
    const thirdParty = composeImages.filter(([, image]) => !firstParty(image));
    expect(thirdParty.length).toBeGreaterThanOrEqual(7);
    for (const [name, image] of thirdParty) {
      expect(image, `compose service ${name}`).toMatch(PINNED);
    }
  });

  it("pins every image the Kubernetes manifests pull", () => {
    const files = k8sFiles("deploy/k8s");
    let seen = 0;
    for (const file of files) {
      for (const image of imageLines(file).filter((i) => !firstParty(i))) {
        seen++;
        expect(image, file).toMatch(PINNED);
      }
    }
    expect(seen).toBeGreaterThanOrEqual(7);
  });

  it("runs the same build of a service in compose and on Kubernetes", () => {
    const k8s = k8sFiles("deploy/k8s").flatMap(imageLines);
    const byRepo = (image: string) => image.split(":")[0];
    for (const [, image] of composeImages.filter(([, i]) => !firstParty(i))) {
      const twin = k8s.filter((i) => byRepo(i) === byRepo(image));
      for (const t of twin) expect(t, `${byRepo(image)} differs between the two`).toBe(image);
    }
  });

  it("pins the one-off containers the scripts start", () => {
    const k8sSetup = readFileSync(resolve("scripts/setup-k8s.sh"), "utf-8");
    const verify = readFileSync(resolve("deploy/notebooks/test/verify-runtime.sh"), "utf-8");
    const runImages = [
      ...[...k8sSetup.matchAll(/--image=(\S+)/g)].map((m) => m[1]),
      ...[...verify.matchAll(/run --rm --network "\$NET" (\S+)/g)].map((m) => m[1]),
    ];
    expect(runImages.length).toBeGreaterThanOrEqual(2);
    for (const image of runImages) expect(image).toMatch(PINNED);
  });

  it("starts per-run Spark clusters on the build the Connect server runs", () => {
    const src = readFileSync(resolve("src/utils/etl/sparkCluster.server.ts"), "utf-8");
    const def = /const DEFAULT_IMAGE =\s*"([^"]+)"/.exec(src)?.[1];
    const server = composeImages.find(([name]) => name === "spark-connect")?.[1];
    expect(def).toMatch(PINNED);
    expect(def).toBe(server);
  });

  it("has Dependabot propose the next pin, for compose and the manifests", () => {
    const cfg = yaml.load(readFileSync(resolve(".github/dependabot.yml"), "utf-8")) as {
      updates: { "package-ecosystem": string; directory?: string; directories?: string[] }[];
    };
    const composeEntry = cfg.updates.find((u) => u["package-ecosystem"] === "docker-compose");
    expect(composeEntry?.directory).toBe("/");
    const docker = cfg.updates.find((u) => u["package-ecosystem"] === "docker");
    const dirs = new Set(
      k8sFiles("deploy/k8s")
        .filter((f) => imageLines(f).some((i) => !firstParty(i)))
        .map((f) => "/" + f.split(/[\\/]/).slice(0, -1).join("/")),
    );
    for (const dir of dirs) expect(docker?.directories, dir).toContain(dir);
  });

  it("scans exactly what compose runs, read from the file", () => {
    const scan = readFileSync(resolve("docs/security/scripts/scan.sh"), "utf-8");
    expect(scan).toContain(`"$REPO/docker-compose.yml" | grep -v '^agentswarms/'`);
    expect(scan).not.toMatch(/^\s+(postgres|ubuntu\/squid|tecnativa|valkey|qdrant)\S*$/m);
  });
});

